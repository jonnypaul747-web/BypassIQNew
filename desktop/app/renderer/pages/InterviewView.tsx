import React, { useState } from 'react';
import { FileText, Sparkles, Download, Loader2, AlertCircle, CheckCircle, Headphones } from 'lucide-react';
import { InterviewLiveView } from './InterviewLiveView.js';
import { FileUpload } from '../components/FileUpload';

interface InterviewQuestion {
  question: string;
  answer: string;
  category: string;
  difficulty: 'Easy' | 'Medium' | 'Hard';
}

interface GenerationResult {
  questions: InterviewQuestion[];
  aiProvider: string;
  aiModel: string;
  documentName: string;
  generatedAt: number;
  cached?: boolean;
  ocrUsed?: boolean;
  usage?: {
    inputTokens: number | null;
    outputTokens: number | null;
    totalTokens: number | null;
  };
}

export function InterviewView() {
  const [file, setFile] = useState<File | null>(null);
  const [generating, setGenerating] = useState(false);
  const [result, setResult] = useState<GenerationResult | null>(null);
  const [error, setError] = useState<string>('');
  const [questionCount, setQuestionCount] = useState(15);
  const [mode, setMode] = useState<'document' | 'live'>('document');
  const [apiReady, setApiReady] = useState(false);

  // Check if electronAPI is available
  React.useEffect(() => {
    const checkApi = setInterval(() => {
      if (window.electronAPI) {
        setApiReady(true);
        clearInterval(checkApi);
      }
    }, 100);

    return () => clearInterval(checkApi);
  }, []);

  const handleFileSelect = (selectedFile: File) => {
    setFile(selectedFile);
    setError('');
  };

  const handleGenerate = async () => {
    if (!file) {
      setError('Please select a file first');
      return;
    }

    if (!apiReady || !window.electronAPI) {
      setError('Electron API not ready. Please wait and try again.');
      return;
    }

    setGenerating(true);
    setError('');
    setResult(null);

    try {
      const filePath = file.path || (file as any).webkitRelativePath;
      // The backend scans the uploaded document and generates the Q&A with a small token budget.
      const response = await window.electronAPI.generateInterviewQuestionsFromBackend(filePath, questionCount);

      if (response.success && response.data) {
        setResult({
          questions: response.data.questions,
          aiProvider: response.data.provider,
          aiModel: response.data.model,
          documentName: response.data.documentName,
          generatedAt: Date.now(),
          cached: response.data.cached,
          ocrUsed: response.data.ocrUsed,
          usage: response.data.usage,
        });
      } else {
        setError(response.error || 'Failed to generate questions');
      }
    } catch (err: any) {
      setError(err.message || 'An error occurred');
    } finally {
      setGenerating(false);
    }
  };

  const handleDownload = () => {
    if (!result) return;

    const content = result.questions.map((q, index) => {
      return `
## Question ${index + 1} (${q.difficulty}) - ${q.category}

**Question:** ${q.question}

**Answer:** ${q.answer}

---
`;
    }).join('\n');

    const fullContent = `# Interview Questions Generated from ${result.documentName}

**Generated by:** JustCilledAI
**AI Provider:** ${result.aiProvider}
**AI Model:** ${result.aiModel}
**Generated at:** ${new Date(result.generatedAt).toLocaleString()}
**Total Questions:** ${result.questions.length}

${content}
`;

    const blob = new Blob([fullContent], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `interview-questions-${Date.now()}.md`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const getDifficultyColor = (difficulty: string) => {
    switch (difficulty) {
      case 'Easy': return 'text-green-400 bg-green-400/10';
      case 'Medium': return 'text-yellow-400 bg-yellow-400/10';
      case 'Hard': return 'text-red-400 bg-red-400/10';
      default: return 'text-gray-400 bg-gray-400/10';
    }
  };

  return (
    <div className="max-w-6xl mx-auto p-6">
      <div className="mb-8">
        <h1 className="text-3xl font-bold text-white mb-2 flex items-center gap-3">
          <Sparkles className="w-8 h-8 text-purple-400" />
          Interview Question Generator
        </h1>
        <p className="text-gray-400">
          Upload a resume, CV, or job description. The backend scans the text and generates question/answer pairs
          with AI, sending only the most relevant part of the document to keep token usage low.
        </p>
      </div>

      {/* Mode switch: document → Q&A, live → system audio (teacher) only */}
      <div className="flex items-center gap-2 mb-6">
        <button
          onClick={() => setMode('document')}
          className={`flex items-center gap-2 px-4 py-2 rounded-lg text-sm font-medium transition-colors border ${
            mode === 'document'
              ? 'bg-slate-800 text-emerald-400 border-slate-700'
              : 'bg-slate-900/40 text-slate-400 border-slate-800 hover:text-slate-200'
          }`}
        >
          <FileText className="w-4 h-4" />
          Document Q&amp;A
        </button>
        <button
          onClick={() => setMode('live')}
          className={`flex items-center gap-2 px-4 py-2 rounded-lg text-sm font-medium transition-colors border ${
            mode === 'live'
              ? 'bg-slate-800 text-emerald-400 border-slate-700'
              : 'bg-slate-900/40 text-slate-400 border-slate-800 hover:text-slate-200'
          }`}
        >
          <Headphones className="w-4 h-4" />
          Live Class
        </button>
      </div>

      {mode === 'live' && <InterviewLiveView />}

      {mode === 'document' && (
        <>
      {/* Upload Section */}
      <div className="bg-slate-800/50 rounded-xl p-6 mb-6 border border-slate-700">
        <div className="flex items-center gap-4 mb-4">
          <label className="text-sm text-gray-300 min-w-[120px]">Number of Questions:</label>
          <input
            type="number"
            min="5"
            max="30"
            value={questionCount}
            onChange={(e) => setQuestionCount(Math.min(30, Math.max(5, parseInt(e.target.value) || 15)))}
            className="bg-slate-700 text-white px-3 py-2 rounded-lg border border-slate-600 w-32"
          />
        </div>

        <div className="border-2 border-dashed border-slate-600 rounded-lg p-8 text-center hover:border-purple-500 transition-colors">
          <FileUpload
            onFileSelect={handleFileSelect}
            selectedFile={file}
            onClear={() => setFile(null)}
            variant="dashed"
            className="w-full"
          />
        </div>

        {error && (
          <div className="mt-4 flex items-center gap-2 text-red-400 bg-red-400/10 px-4 py-2 rounded-lg">
            <AlertCircle className="w-5 h-5" />
            <span>{error}</span>
          </div>
        )}

        <button
          onClick={handleGenerate}
          disabled={!file || generating}
          className="mt-4 w-full bg-purple-600 hover:bg-purple-700 disabled:bg-slate-600 disabled:cursor-not-allowed text-white font-medium py-3 px-6 rounded-lg flex items-center justify-center gap-2 transition-colors"
        >
          {generating ? (
            <>
              <Loader2 className="w-5 h-5 animate-spin" />
              Generating Questions...
            </>
          ) : (
            <>
              <Sparkles className="w-5 h-5" />
              Generate {questionCount} Interview Questions
            </>
          )}
        </button>
      </div>

      {/* Results Section */}
      {result && (
        <div className="bg-slate-800/50 rounded-xl p-6 border border-slate-700">
          <div className="flex items-center justify-between mb-6">
            <div className="flex items-center gap-3">
              <CheckCircle className="w-6 h-6 text-green-400" />
              <div>
                <h2 className="text-xl font-bold text-white">Questions Generated Successfully</h2>
                <p className="text-sm text-gray-400">
                  {result.questions.length} questions • {result.aiProvider} ({result.aiModel})
                  {result.ocrUsed ? ' • OCR (scanned PDF)' : ''}
                  {result.cached
                    ? ' • cached (no tokens used)'
                    : result.usage && result.usage.totalTokens !== null
                      ? ` • ${result.usage.totalTokens} tokens used`
                      : ''}
                </p>
              </div>
            </div>
            <button
              onClick={handleDownload}
              className="bg-green-600 hover:bg-green-700 text-white font-medium py-2 px-4 rounded-lg flex items-center gap-2 transition-colors"
            >
              <Download className="w-5 h-5" />
              Download as Markdown
            </button>
          </div>

          <div className="space-y-6">
            {result.questions.map((q, index) => (
              <div key={index} className="bg-slate-900/50 rounded-lg p-5 border border-slate-700">
                <div className="flex items-start justify-between mb-3">
                  <span className={`px-3 py-1 rounded-full text-xs font-medium ${getDifficultyColor(q.difficulty)}`}>
                    {q.difficulty}
                  </span>
                  <span className="text-xs text-gray-400 bg-slate-700 px-2 py-1 rounded">
                    {q.category}
                  </span>
                </div>

                <h3 className="text-lg font-semibold text-white mb-3">
                  Q{index + 1}: {q.question}
                </h3>

                <div className="text-gray-300 leading-relaxed whitespace-pre-wrap">
                  <strong className="text-purple-400">Answer:</strong> {q.answer}
                </div>
              </div>
            ))}
          </div>
        </div>
      )}
        </>
      )}
    </div>
  );
}
